# Shared helpers for scripts/tailscale/*.sh (sourced, not executed).
# Tailnet as code: docs/plans/2026-11-17-tailnet-as-code.md
#
# Same conventions as scripts/fern/ (whose lib.sh this reuses): idempotent,
# paste-only, never prints a secret, ends with a REPORT BACK block. The admin
# OAuth client secret is read from sops into an UNEXPORTED shell variable and
# handed to tofu only as a per-command environment prefix (`tf …`): it never
# reaches argv, the terminal, a file or this shell's exported environment.
# shellcheck shell=bash
# shellcheck disable=SC2034

# shellcheck source=scripts/fern/lib.sh
. "$(cd "$(dirname "${BASH_SOURCE[0]}")/../fern" && pwd)/lib.sh"

TS_INFRA="$REPO/infra/tailscale"
TS_BACKEND="$TS_INFRA/backend.hcl"
AWS_BACKEND="$REPO/infra/aws/backend.hcl"
ADMIN_REL=secrets/admin/tailscale-admin.yaml
ADMIN_FILE="$REPO/$ADMIN_REL"
ADMIN_KEY=tailscale_admin_oauth
STATE_KEY=tailscale/terraform.tfstate
PLAN_FILE=tailnet.tfplan

# Scopes the admin client must have (write), and the optional ones that turn
# on more management. Names: https://tailscale.com/kb/1623/trust-credentials
REQUIRED_SCOPES="policy_file dns"
OPTIONAL_SCOPES="feature_settings networking_settings oauth_keys devices:core auth_keys"

# `has_scope <scope>`: the admin token (TS_SCOPES) grants <scope> with write
# access ("all" covers everything; "<scope>:read" does not count).
has_scope() {
  case " $TS_SCOPES " in
    *" all "* | *" $1 "*) return 0 ;;
    *) return 1 ;;
  esac
}

# infra/tailscale/backend.hcl from infra/aws/backend.hcl: same bucket,
# region and locking, key tailscale/terraform.tfstate. Sets BACKEND_STATE.
write_backend() {
  [ -r "$AWS_BACKEND" ] || die "$AWS_BACKEND is missing (fern runbook phase 1 creates it)"
  local bucket region tmp
  bucket=$(sed -n 's/^bucket *= *"\(.*\)".*/\1/p' "$AWS_BACKEND" | head -n1)
  region=$(sed -n 's/^region *= *"\(.*\)".*/\1/p' "$AWS_BACKEND" | head -n1)
  [ -n "$bucket" ] && [ -n "$region" ] || die "bucket/region missing in $AWS_BACKEND"
  tmp=$(mktemp)
  cat >"$tmp" <<HCL
# Local only (gitignored). Generated by scripts/tailscale/lib.sh from
# infra/aws/backend.hcl; re-generated on every run.
bucket       = "$bucket"
key          = "$STATE_KEY"
region       = "$region"
use_lockfile = true
encrypt      = true
HCL
  if [ -e "$TS_BACKEND" ] && cmp -s "$tmp" "$TS_BACKEND"; then
    rm -f "$tmp"
    BACKEND_STATE=unchanged
  else
    mv "$tmp" "$TS_BACKEND"
    BACKEND_STATE=written
  fi
}

# Loads the admin client from sops into TS_ADMIN_ID / TS_ADMIN_SECRET
# (unexported), exchanges it for a token to learn the granted scopes
# (TS_SCOPES) and fails on missing required scopes.
load_admin() {
  [ -e "$ADMIN_FILE" ] || die "$ADMIN_REL is missing: run 'bash scripts/tailscale/store-admin.sh' first"
  TS_ADMIN_SECRET=$(sops decrypt --extract "[\"$ADMIN_KEY\"]" "$ADMIN_FILE") ||
    die "could not decrypt $ADMIN_REL (primary age key in ~/.config/sops/age/keys.txt?)"
  TS_ADMIN_ID=$(printf '%s' "$TS_ADMIN_SECRET" | cut -d- -f3)
  ts_token "$TS_ADMIN_SECRET" || die "Tailscale rejected the stored admin client (deleted/rotated? re-run store-admin.sh)"
  unset TS_TOKEN
  local s lacking=
  for s in $REQUIRED_SCOPES; do has_scope "$s" || lacking="$lacking $s"; done
  [ -z "$lacking" ] || die "the admin client lacks write scope(s):$lacking (granted: $TS_SCOPES)"
}

# `tf args…`: tofu with the admin credential in ITS environment only.
tf() {
  TAILSCALE_OAUTH_CLIENT_ID="$TS_ADMIN_ID" \
    TAILSCALE_OAUTH_CLIENT_SECRET="$TS_ADMIN_SECRET" \
    TAILSCALE_TAILNET="${TAILSCALE_TAILNET:--}" \
    command tofu "$@"
}

# Decides what is managed (TF_VAR_*), from scopes and opt-ins. Sets the
# MANAGE_* words for the report.
set_management() {
  if has_scope feature_settings; then
    export TF_VAR_manage_tailnet_settings=true
    MANAGE_SETTINGS=yes
  else
    export TF_VAR_manage_tailnet_settings=false
    MANAGE_SETTINGS="no (scope feature_settings missing)"
  fi

  export TF_VAR_hosts_oauth_client_id=
  if ! has_scope oauth_keys; then
    MANAGE_HOSTS_CLIENT="no (scope oauth_keys missing)"
  elif [ ! -e "$OAUTH_FILE" ]; then
    MANAGE_HOSTS_CLIENT="no (secrets/shared/tailscale-oauth.yaml missing)"
  else
    local hosts_secret
    hosts_secret=$(sops decrypt --extract '["tailscale_oauth"]' "$OAUTH_FILE") ||
      die "could not decrypt secrets/shared/tailscale-oauth.yaml"
    TF_VAR_hosts_oauth_client_id=$(printf '%s' "$hosts_secret" | cut -d- -f3)
    unset hosts_secret
    MANAGE_HOSTS_CLIENT=yes
  fi

  if [ "${TAILNET_DEVICE_TAGS:-0}" != 1 ]; then
    export TF_VAR_manage_device_tags=false
    MANAGE_DEVICES="no (opt-in: TAILNET_DEVICE_TAGS=1)"
  elif ! has_scope devices:core; then
    export TF_VAR_manage_device_tags=false
    MANAGE_DEVICES="no (scope devices:core missing)"
  else
    export TF_VAR_manage_device_tags=true
    MANAGE_DEVICES=yes
  fi
}

# infra/tailscale/hosts.auto.tfvars.json (gitignored) from the hosts
# registry: tagged hosts only, MagicDNS label + tags. No IDs.
write_hosts_tfvars() {
  local tmp domain
  tmp=$(mktemp)
  # shellcheck disable=SC2016 # a Nix expression, not shell
  nix eval --json "$REPO#hosts" --apply '
    hosts: builtins.mapAttrs (n: h: { name = h.tailnetName or n; tags = h.tags; })
      (builtins.removeAttrs hosts (builtins.filter (n: (hosts.${n}.tags or []) == [])
        (builtins.attrNames hosts)))' >"$tmp.hosts" || die "nix eval .#hosts failed"
  domain=$(nix eval --raw "$REPO#tailnet.domain") || die "nix eval .#tailnet.domain failed"
  jq -n --slurpfile h "$tmp.hosts" --arg d "$domain" \
    '{tagged_hosts: $h[0], tailnet_domain: $d}' >"$tmp" || die "could not build hosts.auto.tfvars.json"
  rm -f "$tmp.hosts"
  mv "$tmp" "$TS_INFRA/hosts.auto.tfvars.json"
  TAGGED_HOSTS=$(jq -r '.tagged_hosts | keys | join(",")' "$TS_INFRA/hosts.auto.tfvars.json")
}

# Everything plan.sh and apply.sh share, up to `tofu init`.
prepare() {
  need opentofu:tofu jq:jq curl:curl sops:sops -- "$@"
  write_backend
  load_admin
  set_management
  write_hosts_tfvars
  cd "$TS_INFRA"
  log "tofu init (S3 backend, key $STATE_KEY)"
  tf init -input=false -reconfigure -backend-config=backend.hcl >/dev/null ||
    die "tofu init failed (AWS credentials for the state bucket? AWS_PROFILE)"
}

# `make_plan`: tofu plan -out (imports are import blocks: no state write).
# Sets PLAN_RC (0 no changes, 2 changes) and prints the plan.
make_plan() {
  trap 'shred -u "$TS_INFRA/$PLAN_FILE" 2>/dev/null || true' EXIT
  log "tofu plan (validates the policy and its tests against the API)"
  set +e
  local extra=()
  # Rotation of the hosts client (needs prevent_destroy removed in oauth.tf).
  if [ "${TAILNET_REPLACE_HOSTS_CLIENT:-0}" = 1 ]; then
    warn "TAILNET_REPLACE_HOSTS_CLIENT=1: planning a NEW hosts OAuth client (old one deleted)"
    extra+=(-replace='tailscale_oauth_client.hosts[0]')
  fi
  tf plan -input=false -no-color -detailed-exitcode -out="$PLAN_FILE" "${extra[@]}"
  PLAN_RC=$?
  set -e
  [ "$PLAN_RC" = 1 ] && die "tofu plan failed (see above)"
  return 0
}

# One line per resource action, and the live values of imported settings/DNS
# (not secret) so they can be pinned in HCL.
plan_report() {
  local json
  json=$(tf show -json "$PLAN_FILE")
  printf '%s' "$json" | jq -r '
    .resource_changes[]? as $r
    | ($r.change.actions | join("+")) as $a
    | (if $r.change.importing then "import" else "" end) as $i
    | select($a != "no-op" or $i != "")
    | "  \($r.address): \([$i, (if $a == "no-op" then empty else $a end)] | map(select(. != "")) | join(" + "))"'
  printf '%s' "$json" | jq -r '
    "  summary: import=\([.resource_changes[]? | select(.change.importing)] | length)"
    + " create=\([.resource_changes[]? | select(.change.actions == ["create"])] | length)"
    + " update=\([.resource_changes[]? | select(.change.actions == ["update"])] | length)"
    + " replace=\([.resource_changes[]? | select(.change.actions | length == 2)] | length)"
    + " delete=\([.resource_changes[]? | select(.change.actions == ["delete"])] | length)"'
  printf '%s' "$json" | jq -c '
    .resource_changes[]? | select(.type == "tailscale_tailnet_settings")
    | "  live tailnet_settings: \(.change.before // {} | del(.id))"' -r
  printf '%s' "$json" | jq -c '
    .resource_changes[]? | select(.type == "tailscale_dns_configuration")
    | "  live dns: \(.change.before // {} | del(.id))"' -r
}
