def notify(body, urgency="normal", ms=6000):
    try:
        subprocess.run([CFG["bin"]["notify-send"], "-a", "Dictation", "-i",
                        "audio-input-microphone", "-u", urgency, "-t", str(ms),
                        "Dictation", body], timeout=5,
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    except (OSError, subprocess.SubprocessError):
        pass


def type_text(text):
    mode = CFG["output"]
    if mode == "none":
        return
    if mode == "print":
        sys.stdout.write(text)
        sys.stdout.flush()
        return
    try:
        if mode == "paste":
            subprocess.run([CFG["bin"]["wl-copy"], "--", text], check=True, timeout=5)
            subprocess.run([CFG["bin"]["wtype"], "-M", "ctrl", "-M", "shift", "-k", "v",
                            "-m", "shift", "-m", "ctrl"], check=True, timeout=10)
        else:
            subprocess.run([CFG["bin"]["wtype"], "--", text], check=True, timeout=30)
    except (OSError, subprocess.SubprocessError):
        try:
            subprocess.run([CFG["bin"]["wl-copy"], "--", text], timeout=5)
            notify(f"Couldn't type; copied to the clipboard: {text}")
        except (OSError, subprocess.SubprocessError):
            notify(f"Couldn't type: {text}")


def journal_append(sid, text, when=None, note=""):
    d = os.path.expanduser(CFG["journal_dir"])
    os.makedirs(d, mode=0o700, exist_ok=True)
    when = when or time.localtime()
    path = os.path.join(d, time.strftime("%Y-%m-%d", when) + ".md")
    line = f"- {time.strftime('%H:%M:%S', when)} · {sid}{note} · {text}\n"
    fd = os.open(path, os.O_WRONLY | os.O_APPEND | os.O_CREAT, 0o600)
    try:
        os.write(fd, line.encode())
        os.fsync(fd)
    finally:
        os.close(fd)


class Bar:
    """Waybar refresh by signal (custom/dictation), only while a session runs."""

    def __init__(self):
        self.pid = None
        self.sig = signal.SIGRTMIN + CFG["waybar_signal"]

    def _resolve(self):
        try:
            out = subprocess.run(
                [CFG["bin"]["systemctl"], "--user", "show", "-p", "MainPID",
                 "--value", "waybar.service"], capture_output=True, text=True, timeout=3)
            pid = int(out.stdout.strip() or 0)
            self.pid = pid or None
        except (OSError, ValueError, subprocess.SubprocessError):
            self.pid = None

    def refresh(self):
        if self.pid is None:
            self._resolve()
        if self.pid:
            try:
                os.kill(self.pid, self.sig)
            except OSError:
                self.pid = None


def write_state(state):
    """The bar/key state, only while this process is the current session."""
    import fcntl
    with open(os.path.join(STATE_DIR, "lock"), "a") as lk:
        fcntl.flock(lk, fcntl.LOCK_EX)
        try:
            with open(os.path.join(STATE_DIR, "pid")) as f:
                if f.read().strip() != str(os.getpid()):
                    return
        except OSError:
            return
        with open(os.path.join(STATE_DIR, "state"), "w") as f:
            f.write(state)


