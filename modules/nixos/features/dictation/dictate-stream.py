"""dictate-stream: dictation sessions for `dictate`, always backed by a draft.

One recording runs continuously; Silero VAD cuts it at natural pauses
(`pause_ms` of silence) or, in continuous speech, at the quietest point
before `max_segment_sec`. Each segment is transcribed as soon as it closes
(the session's backend: the first reachable whisper-server, else the local
engine) while recording goes on. Two modes, same pipeline:
  batch   the text is pasted at once, at the end (default)
  stream  each segment is typed as soon as it is transcribed, in order

Drafts: every session records into ~/.local/state/dictation/drafts/<id>/
(persistent disk): audio.pcm (raw s16le 16 kHz mono, append-only, fsynced
every 2 s and after each segment: whatever reached the disk stays readable
after a power cut), meta.json (status, language, mode, backend; written
atomically), commits.jsonl (one line per transcribed segment) and
transcript.txt. Status: recording -> transcribing -> done | pending, or
cancelled. A draft stays `pending` until its text is typed or copied; `done`
and `cancelled` drafts are compressed to Opus and pruned after keep_days.

  dictate-stream record [--lang L] [--t0 MS] [--mode M]
                        live session (SIGUSR1/SIGTERM stop, SIGUSR2 cancels)
  dictate-stream file WAV [--stream] [--mode M] [--realtime] [--overlay]
  dictate-stream drafts [--json]
  dictate-stream recover [ID | --latest] [--type | --copy] [--all] [--fresh]
  dictate-stream discard ID
  dictate-stream prune [--check]   prune old drafts; --check: notify pending
  dictate-stream push [--all | ID] upload delivered drafts to the training lab
  dictate-stream input [--json] [--set NODE|auto]
                        the mics, and which one sessions record from

Config: JSON file in $DICTATE_CONFIG (generated by the dictation feature);
DICTATE_SERVERS (space separated, may be empty), DICTATE_LANG,
DICTATE_OUTPUT (type|paste|print|none) and DICTATE_JOURNAL_DIR override it.
"""

