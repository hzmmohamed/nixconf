TERMINALS = ("kitty", "foot", "alacritty", "wezterm", "ghostty", "konsole",
             "terminal", "xterm")


def focused_app():
    try:
        out = subprocess.run([CFG["bin"]["swaymsg"], "-t", "get_tree", "-r"],
                             capture_output=True, timeout=3)
        stack = [json.loads(out.stdout)]
    except (OSError, ValueError, subprocess.SubprocessError):
        return ""
    while stack:
        n = stack.pop()
        if n.get("focused"):
            return (n.get("app_id") or (n.get("window_properties") or {}).get("class") or "").lower()
        stack += n.get("nodes", []) + n.get("floating_nodes", [])
    return ""


def save_clipboard():
    """(type, bytes) of the current clipboard, or None (empty, or a password)."""
    paste = CFG["bin"]["wl-paste"]
    try:
        types = subprocess.run([paste, "--list-types"], capture_output=True, text=True,
                               timeout=2).stdout.split()
        if not types or "x-kde-passwordManagerHint" in types:
            return None
        t = next((t for t in ("text/plain;charset=utf-8", "text/plain") if t in types), types[0])
        data = subprocess.run([paste, "--no-newline", "--type", t], capture_output=True,
                              timeout=2, check=True).stdout
        return t, data
    except (OSError, subprocess.SubprocessError):
        return None


def restore_clipboard(saved):
    try:
        if saved is None:
            subprocess.run([CFG["bin"]["wl-copy"], "--clear"], timeout=2)
        else:
            subprocess.run([CFG["bin"]["wl-copy"], "--type", saved[0]], input=saved[1],
                           timeout=2, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    except (OSError, subprocess.SubprocessError):
        pass


def paste_text(text):
    """The whole text at once: clipboard + the focused app's paste key, then
    the previous clipboard back. Terminals paste with Ctrl+Shift+V; elsewhere
    Ctrl+V (Ctrl+Shift+V is something else in editors)."""
    saved = save_clipboard()
    subprocess.run([CFG["bin"]["wl-copy"], "--type", "text/plain;charset=utf-8", "--", text],
                   check=True, timeout=5)
    app = focused_app()
    mods = ["ctrl", "shift"] if any(t in app for t in TERMINALS) else ["ctrl"]
    keys = [CFG["bin"]["wtype"]]
    for m in mods:
        keys += ["-M", m]
    keys += ["-k", "v"]
    for m in reversed(mods):
        keys += ["-m", m]
    subprocess.run(keys, check=True, timeout=10)
    time.sleep(0.5)  # the app reads the selection asynchronously
    restore_clipboard(saved)


def deliver(text, how=None):
    """Type / paste / copy / print `text`; how it got out, or None."""
    mode = how or CFG["output"]
    if mode == "none":
        return "none"
    if mode == "print":
        sys.stdout.write(text)
        sys.stdout.flush()
        return "print"
    if mode == "copy":
        return "clipboard" if copy_text(text) else None
    try:
        if mode == "paste":
            paste_text(text)
            return "pasted"
        subprocess.run([CFG["bin"]["wtype"], "--", text], check=True, timeout=180)
        return "typed"
    except (OSError, subprocess.SubprocessError):
        if copy_text(text):
            notify(f"Couldn't type; copied to the clipboard: {text[:200]}")
            return "clipboard"
        return None


def journal_append(sid, text, when=None, note=""):
    d = os.path.expanduser(CFG["journal_dir"])
    os.makedirs(d, mode=0o700, exist_ok=True)
    when = when or time.localtime()
    path = os.path.join(d, time.strftime("%Y-%m-%d", when) + ".md")
    line = f"- {time.strftime('%H:%M:%S', when)} · {sid}{note} · {text}\n"
    fd = os.open(path, os.O_WRONLY | os.O_APPEND | os.O_CREAT, 0o600)
    try:
        os.write(fd, line.encode())
        os.fsync(fd)
    finally:
        os.close(fd)


class Bar:
    """Waybar refresh by signal (custom/dictation), only while a session runs."""

    def __init__(self):
        self.pid = None
        self.sig = signal.SIGRTMIN + CFG["waybar_signal"]

    def _resolve(self):
        try:
            out = subprocess.run(
                [CFG["bin"]["systemctl"], "--user", "show", "-p", "MainPID",
                 "--value", "waybar.service"], capture_output=True, text=True, timeout=3)
            self.pid = int(out.stdout.strip() or 0) or None
        except (OSError, ValueError, subprocess.SubprocessError):
            self.pid = None

    def refresh(self):
        if self.pid is None:
            self._resolve()
        if self.pid:
            try:
                os.kill(self.pid, self.sig)
            except OSError:
                self.pid = None


