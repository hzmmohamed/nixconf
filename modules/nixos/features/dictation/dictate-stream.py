def cmd_record(args):
    rec = RECORDER
    stop = {"why": None}
    if rec is None:
        write_state("idle")
        Bar().refresh()
        notify("No microphone connected: connect the headset, then dictate again.",
               "critical", 0)
        return

    def on_signal(sig, _frame):
        stop["why"] = "cancel" if sig == signal.SIGUSR2 else "stop"
        try:
            rec.terminate()
        except OSError:
            pass

    for s in (signal.SIGUSR1, signal.SIGTERM, signal.SIGINT, signal.SIGUSR2):
        signal.signal(s, on_signal)

    lang = args.lang or os.environ.get("DICTATE_LANG") or CFG["default_lang"]
    mode = args.mode or CFG["mode"]
    t0 = (args.t0 / 1000.0) if args.t0 else time.time()
    app = focused_app()  # the recorder is already running: this costs no audio
    draft = Draft.create(lang, mode, "mic", journal=True, t0=t0, app=app,
                         tier=tier_for(app, CFG.get("work_apps", []), args.tier))
    mic = INPUT["label"]
    draft.save(input=mic)
    write_input(mic)
    sess = Session(draft, mode, overlay=CFG["overlay"]["enable"], stream_print=False)
    seg = Segmenter(Vad(CFG["vad_model"]), CFG["pause_ms"], CFG["max_segment_sec"])
    bar = Bar()
    bar.refresh()

    def housekeeping():
        prune()
        attention_notice(exclude=draft.path)

    threading.Thread(target=housekeeping, daemon=True).start()
    if not CFG["overlay"]["enable"]:
        notify(f"Listening ({lang.upper()}) on {mic}…", "low", 3000)
    if INPUT["note"]:
        notify(f"{INPUT['note'].capitalize()}; using {mic}. Change it in "
               "“Dictation drafts” → Microphone.", "normal", 5000)
    # A headset playing for another device (multipoint) gives pure zeros.
    started = time.monotonic()
    heard = INPUT["kind"] != "headset"
    # Watchdog: a mic that gives no speech in the first `no_speech_sec`, or
    # only digital silence / no audio at all for that long later on (muted,
    # gone, busy elsewhere), stops the session with a persistent error
    # instead of recording nothing for minutes.
    quiet_sec = CFG["no_speech_sec"]
    speech_seen = False
    last_sound = last_data = started
    max_sec = CFG["max_sec"]
    last_tick = last_push = last_sync = time.monotonic()
    last_keep = last_tick
    level_acc, level_n = 0.0, 0
    pending = b""
    fd = rec.stdout.fileno()

    def give_up(why):
        if stop["why"] is None:
            stop["why"] = "error"
            sess.error = (f"Stopped: {why}. Check the mic (connected, not muted, "
                          "not busy with another device) or pick another in "
                          "“Dictation drafts” → Microphone.")
            try:
                rec.terminate()
            except OSError:
                pass

    while True:
        ready, _, _ = select.select([fd], [], [], 1.0)
        now = time.monotonic()
        if not ready:
            if quiet_sec and now - last_data >= quiet_sec:
                give_up(f"no audio from {mic} for {quiet_sec} s")
            continue
        data = os.read(fd, 4096)
        if not data:
            break
        last_data = now
        draft.write_audio(data)
        pending += data
        if data.count(0) != len(data):
            last_sound = now
        if not heard:
            if data.count(0) != len(data):
                heard = True
                if sess.warning:
                    sess.warning = ""
            elif now - started >= 3 and not sess.warning:
                sess.warning = f"No sound from {mic}: is it busy with another device?"
                notify(f"No sound from {mic}. If it is playing for another device "
                       "(your phone), pause it there, or pick another mic in "
                       "“Dictation drafts” → Microphone.", "normal", 8000)
        # Audio time, not wall time: the pipe may still hold unread audio.
        if quiet_sec and not speech_seen and seg.pos >= quiet_sec * RATE:
            give_up(f"no speech heard from {mic} in {quiet_sec} s")
        elif quiet_sec and now - last_sound >= quiet_sec:
            give_up(f"{mic} sent only silence for {quiet_sec} s")
        n = len(pending) // BYTES_PER_FRAME * BYTES_PER_FRAME
        frames, pending = pending[:n], pending[n:]
        for k in range(0, n, BYTES_PER_FRAME):
            f = pcm_to_float(frames[k:k + BYTES_PER_FRAME])
            level_acc += float(np.dot(f, f))
            level_n += len(f)
            for s in seg.feed(f):
                sess.submit(s, time.time())
            speech_seen = speech_seen or seg.speaking
        now = time.monotonic()
        if now - last_sync >= 2:
            draft.sync()
            last_sync = now
        if now - last_push >= 1 / 15 and level_n:
            rms = (level_acc / level_n) ** 0.5
            db = 20 * np.log10(max(rms, 1e-6))  # -60 dBFS .. -12 dBFS -> 0..1
            sess.level = float(min(1.0, max(0.0, (db + 60) / 48)))
            sess.speaking = seg.speaking
            level_acc, level_n = 0.0, 0
            sess.push()
            last_push = now
        if now - last_tick >= 1:
            bar.refresh()
            last_tick = now
        if now - last_keep >= 60:
            threading.Thread(target=sess.backends.keepalive, daemon=True).start()
            last_keep = now
        if time.time() - t0 >= max_sec and stop["why"] is None:
            stop["why"] = "stop"
            notify(f"Stopped at the {max_sec // 60} min safety limit", "normal", 5000)
            rec.terminate()
    rec.wait()
    draft.sync()
    if stop["why"] == "cancel":
        write_state("idle")
        bar.refresh()
        sess.cancel()
        return
    if draft.duration() < 0.05 and stop["why"] is None:
        notify("Recording failed: no audio from the microphone", "critical", 6000)
    write_state("transcribing")
    draft.save(status="transcribing")
    with sess.lock:
        sess.state = "finishing"
    sess.speaking = False
    sess.level = 0.0
    bar.refresh()
    for s in seg.flush():
        sess.submit(s, time.time())
    sess.push()
    sess.drain()
    status = sess.conclude()
    write_state("idle")
    bar.refresh()
    log(f"{status}: {stats(sess.latencies)}")
    if sess.error:
        log(sess.error)
        notify(sess.error, "critical", 0)
    if status == "done":
        draft.compress()
        if CFG.get("lab_url"):
            push(draft, CFG["lab_url"])


def run_file(samples, args, sess, draft):
    seg = Segmenter(Vad(CFG["vad_model"]), CFG["pause_ms"], CFG["max_segment_sec"])
    started = last_sync = time.time()
    for k in range(0, len(samples) - FRAME + 1, FRAME):
        f = samples[k:k + FRAME]
        draft.write_audio((f * 32767).astype(np.int16).tobytes())
        for s in seg.feed(f):
            sess.submit(s, time.time())
        if args.realtime:
            now = time.time()
            if now - last_sync >= 2:
                draft.sync()
                last_sync = now
            ahead = (k + FRAME) / RATE - (now - started)
            if ahead > 0:
                time.sleep(ahead)
            if k % (FRAME * 2) == 0:
                sess.level = float(min(1.0, max(0.0, (20 * np.log10(
                    max(float(np.sqrt(np.mean(f * f))), 1e-6)) + 60) / 48)))
                sess.speaking = seg.speaking
                sess.push()
    draft.sync()
    draft.save(status="transcribing")
    for s in seg.flush():
        sess.submit(s, time.time())
    with sess.lock:
        sess.state = "finishing"
    sess.push()
    sess.drain()


def cmd_file(args):
    samples = read_wav(args.wav)
    lang = os.environ.get("DICTATE_LANG") or CFG["default_lang"]
    mode = args.mode or ("stream" if args.stream else "batch")
    CFG["output"] = "none" if args.stream else "print"
    draft = Draft.create(lang, mode, "file", journal=False, t0=time.time())
    sess = Session(draft, mode, overlay=args.overlay, stream_print=args.stream)
    sess.backends.ready.wait()
    log(f"{mode} mode, {sess.backends.label} ({lang}), {len(samples) / RATE:.1f}s audio, "
        f"pause {CFG['pause_ms']} ms, max segment {CFG['max_segment_sec']} s, draft {draft.id}")
    t = time.time()
    run_file(samples, args, sess, draft)
    status = sess.conclude()
    if not args.stream:
        print()
    log(f"{status}: {stats(sess.latencies)}; total {time.time() - t:.1f}s")
    if status == "pending":
        log(f"draft kept: {draft.path}")
        sys.exit(1)


def recover_draft(d, how, scope_all=False, fresh=False, delay=0.0):
    """Transcribe what a draft has not delivered (or all of it) and deliver it."""
    commits = d.commits()
    complete = d.meta.get("complete", False) and d.status not in ("interrupted",)
    undelivered = any(not c.get("delivered") for c in commits) or not complete
    use_all = scope_all or fresh or not undelivered
    pieces = []  # [start, end, text or None, conf or None]
    if not fresh:
        for c in commits:
            if use_all or not c.get("delivered"):
                pieces.append([c["start"], c["end"], c["text"] if c.get("ok") else None, None])
    samples = None
    if fresh or not complete or any(p[2] is None for p in pieces):
        samples = d.samples()
    if fresh:
        segs = segment_all(samples)
    elif not complete:
        tail = max([c["end"] for c in commits], default=0)
        segs = segment_all(samples[tail:], offset=tail)
    else:
        segs = []
    pieces += [[a, b, None, None] for a, b, _ in segs]
    pieces.sort(key=lambda p: p[0])
    todo = [p for p in pieces if p[2] is None]
    backends = Backends(d.meta.get("lang") or CFG["default_lang"])
    if todo:
        backends.probe()
    where = f" on {backends.label}" if todo else ""
    log(f"{d.id}: {len(pieces)} segments, {len(todo)} to transcribe{where}")
    failed = 0
    for p in todo:
        try:
            raw, p[3] = backends.transcribe(samples[p[0]:p[1]])
            p[2] = clean(raw)
        except Exception as err:
            log(f"segment at {fmt_t(p[0] / RATE)} failed: {err}")
            failed += 1
    backends.close()
    ok = [p for p in pieces if p[2] is not None]

    def record(delivered):
        kept = {} if fresh else {(c["start"], c["end"]): c for c in commits}
        for i, p in enumerate(pieces):
            if p[2] is None:
                continue
            c = kept.get((p[0], p[1]), {"i": i})
            kept[(p[0], p[1])] = dict(c, start=p[0], end=p[1], ok=True, text=p[2],
                                      delivered=bool(delivered or c.get("delivered")))
            if p[3] is not None:
                kept[(p[0], p[1])]["conf"] = p[3]
        d.set_commits(list(kept.values()))

    text = join_texts(p[2] for p in ok if p[2])
    if failed:
        record(False)
        d.save(status="pending", error=f"{failed} segments failed in recovery")
        print(text)
        log(f"{failed} of {len(pieces)} segments failed; the draft stays pending")
        return False
    print(text)
    if how in ("type", "copy") and text:
        if delay:
            time.sleep(delay)
        got = deliver(text + (" " if how == "type" and CFG["append_space"] else ""),
                      "copy" if how == "copy" else None)
        if not got:
            record(False)
            d.save(status="pending", complete=True, error="couldn't type or copy the text")
            return False
        record(True)
        first = d.status not in TERMINAL
        d.save(status="done", complete=True, error=None, delivered=got,
               duration=round(d.duration(), 2))
        if first and d.meta.get("journal", True) and undelivered:
            journal_append(d.meta.get("sid", d.id), text, note=" (recovered)")
        d.compress()
    else:
        record(False)
        if d.status == "interrupted":
            d.save(status="pending", complete=True)
        elif not complete:
            d.save(complete=True)
    return True


def pick(args):
    if args.id:
        return [find_draft(args.id)]
    drafts = list_drafts()
    pending = [d for d in drafts if d.needs_attention]
    if args.latest:
        if pending or drafts:
            return [(pending or drafts)[0]]
        return []
    return pending


def cmd_recover(args):
    drafts = pick(args)
    if not drafts:
        log("no draft to recover")
        return
    how = "type" if args.type else "copy" if args.copy else None
    ok = True
    for d in drafts:
        if d.status in ("recording", "transcribing"):
            log(f"{d.id} is still running; skipped")
            continue
        ok = recover_draft(d, how, args.all, args.fresh, args.delay) and ok
    if not ok:
        sys.exit(1)


def cmd_drafts(args):
    rows = []
    for d in list_drafts():
        text = ""
        try:
            with open(d.file("transcript.txt")) as f:
                text = f.read().strip()
        except OSError:
            pass
        rows.append({"id": d.id, "status": d.status, "duration": round(d.duration(), 1),
                     "mode": d.meta.get("mode"), "lang": d.meta.get("lang"),
                     "started": d.meta.get("started"), "error": d.meta.get("error"),
                     "words": first_words(text), "path": d.path})
    if args.json:
        print(json.dumps(rows, ensure_ascii=False))
        return
    if not rows:
        print("no drafts")
    for r in rows:
        words = r["words"] or ("(not transcribed)" if r["status"] != "done" else "")
        print(f"{r['id']}  {r['status']:<11} {fmt_t(r['duration'])}  {r['mode'] or '?':<6} "
              f"{(r['lang'] or '?').upper():<3} {words}")


def cmd_discard(args):
    d = find_draft(args.id)
    if d.status in ("recording", "transcribing"):
        raise SystemExit(f"dictate: {d.id} is still running (cancel it first)")
    d.discard()
    log(f"discarded {d.id}")


def cmd_input(args):
    """List the mics (and which one the next session uses), or set the choice."""
    if args.set:
        os.makedirs(os.path.dirname(INPUT_FILE), mode=0o700, exist_ok=True)
        if args.set == "auto":
            try:
                os.unlink(INPUT_FILE)
            except FileNotFoundError:
                pass
        else:
            atomic_write(INPUT_FILE, args.set + "\n")
        print(resolve_input(pref=preferred_input())["label"])
        return
    objs = pw_dump()
    inputs, default = list_inputs(objs)
    pref = preferred_input()
    now = resolve_input(objs, pref)
    if args.json:
        print(json.dumps({"preferred": pref, "current": now, "default": default,
                          "inputs": inputs}, ensure_ascii=False))
        return
    print(f"next session: {now['label']}" + (f" ({now['note']})" if now["note"] else ""))
    print(f"choice: {pref or 'auto (newest headset, else the default source)'}")
    for i in inputs:
        mark = "*" if i["name"] == (now["name"] or default) else " "
        print(f"{mark} {i['kind']:<7} {i['label']:<32} {i['name']}")


def cmd_prune(args):
    n = prune(args.keep_days)
    if n:
        log(f"pruned {n} drafts")
    if args.check:
        attention_notice()


def cmd_push(args):
    url = CFG.get("lab_url")
    if not url:
        print("dictate: no lab configured (preferences.dictation.labUrl)")
        return
    drafts = list_drafts() if args.all or not args.id else [find_draft(args.id)]
    sent = sum(push(d, url) for d in drafts if d.status == "done" and not d.meta.get("uploaded"))
    if sent:
        log(f"uploaded {sent} drafts to the lab")


