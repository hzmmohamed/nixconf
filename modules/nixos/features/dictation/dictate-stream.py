class Session:
    """Segments in, committed text out, in order; crash-safe on disk."""

    def __init__(self, lang, t0, source, journal, overlay, stream_print):
        self.sid = time.strftime("%H%M%S") + "-" + uuid.uuid4().hex[:4]
        self.lang = lang
        self.t0 = t0  # wall clock (s) of the key press
        self.journal = journal
        self.stream_print = stream_print
        self.dir = os.path.join(SESSIONS, self.sid)
        os.makedirs(self.dir, mode=0o700)
        with open(os.path.join(self.dir, "meta.json"), "w") as f:
            json.dump({"sid": self.sid, "pid": os.getpid(), "lang": lang,
                       "t0": t0, "source": source, "journal": journal}, f)
        self.audio = open(os.path.join(self.dir, "audio.raw"), "ab", buffering=0)
        self.commits = open(os.path.join(self.dir, "commits.jsonl"), "a", buffering=1)
        self.backends = Backends(lang, on_change=self.changed)
        self.lock = threading.Lock()
        self.next_index = 0  # next segment to be dispatched
        self.next_commit = 0
        self.results = {}
        self.meta = {}  # index -> (start, end, closed_wall, speech_end_wall)
        self.typed = ""
        self.lines = []  # last committed texts (overlay)
        self.failed = False
        self.cancelled = False
        self.latencies = []
        self.work = queue.Queue()
        self.workers = [threading.Thread(target=self._worker, daemon=True)
                        for _ in range(CFG["workers"])]
        for w in self.workers:
            w.start()
        self.overlay = None
        self.ov_lock = threading.Lock()
        if overlay and CFG["bin"].get("overlay"):
            self._spawn_overlay()
        self.level = 0.0
        self.speaking = False
        self.state = "recording"
        threading.Thread(target=self.backends.probe, daemon=True).start()

    # overlay ---------------------------------------------------------------
    def _spawn_overlay(self):
        try:
            argv = shlex.split(CFG["bin"]["overlay"])
            argv += ["--css", CFG["overlay"]["css"],
                     "--long-session-sec", str(CFG["overlay"]["long_session_sec"])]
            self.overlay = subprocess.Popen(
                argv,
                stdin=subprocess.PIPE, stdout=subprocess.DEVNULL,
                stderr=open(os.path.join(STATE_DIR, "overlay.log"), "w"),
                preexec_fn=set_pdeathsig)
        except OSError as err:
            log(f"overlay: {err}")

    def changed(self):
        self.push()

    def push(self):
        ov = self.overlay
        if not ov or ov.poll() is not None:
            return
        with self.lock:
            msg = {"t": round(time.time() - self.t0, 2), "level": round(self.level, 3),
                   "speech": self.speaking, "lang": self.lang.upper(),
                   "backend": self.backends.label, "lines": self.lines[-3:],
                   "pending": self.next_index - self.next_commit, "state": self.state}
        line = (json.dumps(msg, ensure_ascii=False) + "\n").encode()
        with self.ov_lock:
            try:
                ov.stdin.write(line)
                ov.stdin.flush()
            except (OSError, ValueError):
                self.overlay = None

    # audio in --------------------------------------------------------------
    def save_audio(self, pcm):
        self.audio.write(pcm)

    def submit(self, seg, now_wall):
        start, end, samples = seg
        with self.lock:
            i = self.next_index
            self.next_index += 1
            self.meta[i] = (start, end, now_wall)
        self.work.put((i, samples))
        self.push()

    # transcription ---------------------------------------------------------
    def _worker(self):
        while True:
            item = self.work.get()
            if item is None:
                return
            i, samples = item
            text, ok = "", False
            # Every segment gets a result, whatever happens: a gap would stall
            # the in-order commit.
            try:
                if not self.cancelled:
                    delay = float(os.environ.get("DICTATE_TEST_JITTER", "0"))
                    if delay:
                        time.sleep(random.uniform(0, delay))
                    prompt = (CFG["prompt"] + " " + self.typed[-200:]).strip()
                    text, ok = clean(self.backends.transcribe(samples, prompt)), True
                    if delay:
                        log(f"segment {i} transcribed (next to commit: {self.next_commit})")
            except Exception as err:
                log(f"segment {i}: {err}")
            with self.lock:
                self.results[i] = (text, ok)
            self._commit_ready()

    def _commit_ready(self):
        while True:
            with self.lock:
                i = self.next_commit
                if i not in self.results or self.cancelled:
                    return
                text, ok = self.results.pop(i)
                start, end, closed = self.meta.pop(i)
            try:
                self._commit(i, start, end, closed, text, ok)
            except Exception as err:
                log(f"commit {i}: {err}")
            finally:
                with self.lock:
                    self.next_commit += 1
            self.push()

    def _commit(self, i, start, end, closed, text, ok):
        out = joined(self.typed, text)
        if out:
            type_text(out)
            self.typed += out
        now = time.time()
        lat = now - closed
        self.latencies.append(lat)
        if not ok:
            self.failed = True
        self.commits.write(json.dumps({"i": i, "start": start, "end": end,
                                       "ok": ok, "text": text}, ensure_ascii=False) + "\n")
        os.fsync(self.commits.fileno())
        if text:
            with self.lock:
                self.lines.append(text)
                del self.lines[:-3]
            if self.journal:
                journal_append(self.sid, text)
        if self.stream_print:
            print(f"[{fmt_t(start / RATE)}.{int(start / RATE * 10) % 10}"
                  f"–{fmt_t(end / RATE)}.{int(end / RATE * 10) % 10}] #{i} "
                  f"+{lat:.2f}s {'' if ok else '(FAILED) '}{text}", flush=True)

    # end -------------------------------------------------------------------
    def drain(self):
        """Wait until every dispatched segment is committed."""
        while True:
            with self.lock:
                if self.next_commit >= self.next_index or self.cancelled:
                    break
            time.sleep(0.02)

    def finish(self, cancelled=False):
        self.cancelled = self.cancelled or cancelled
        for _ in self.workers:
            self.work.put(None)
        self.backends.close()
        self.audio.close()
        self.commits.close()
        if self.overlay:
            with self.ov_lock:
                try:
                    self.overlay.stdin.close()
                except OSError:
                    pass
        if self.cancelled or not self.failed:
            shutil.rmtree(self.dir, ignore_errors=True)
        else:
            notify("Some segments failed to transcribe; their audio is kept. "
                   "Run `dictate recover` to retry.", "critical", 10000)


def stats(lat):
    if not lat:
        return "no segments"
    a = sorted(lat)
    return (f"{len(a)} segments, commit latency after close: median {a[len(a) // 2]:.2f}s, "
            f"max {a[-1]:.2f}s")


