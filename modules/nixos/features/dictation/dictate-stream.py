# --- VAD segmenter ------------------------------------------------------------
class Vad:
    """Silero VAD (v5/v6 ONNX interface): speech probability per 512 samples."""

    CONTEXT = 64

    def __init__(self, path):
        opts = onnxruntime.SessionOptions()
        opts.intra_op_num_threads = 1
        opts.inter_op_num_threads = 1
        self.sess = onnxruntime.InferenceSession(
            path, sess_options=opts, providers=["CPUExecutionProvider"])
        self.state = np.zeros((2, 1, 128), dtype=np.float32)
        self.context = np.zeros(self.CONTEXT, dtype=np.float32)
        self.sr = np.array(RATE, dtype=np.int64)

    def __call__(self, frame):
        x = np.concatenate([self.context, frame])[None, :]
        out, self.state = self.sess.run(
            None, {"input": x, "state": self.state, "sr": self.sr})
        self.context = frame[-self.CONTEXT:]
        return float(out[0][0])


class Segmenter:
    """Speech segments from a stream of frames, as sample ranges.

    Opens at the first frame above `threshold` (minus `pad_pre`), closes
    after `pause` of frames below `threshold - 0.15` (plus `pad_post`), and
    splits a segment longer than `max_len` at the quietest ~100 ms of its
    last 40 %. Bursts with less than `min_speech` voiced audio are dropped.
    """

    def __init__(self, vad, pause_ms, max_sec, threshold=0.5):
        self.vad = vad
        self.on = threshold
        self.off = threshold - 0.15
        self.pause = pause_ms * RATE // 1000
        self.max_len = int(max_sec * RATE)
        self.pad_pre = RATE // 5
        self.pad_post = RATE * 3 // 20
        self.min_speech = RATE // 4
        self.frames = []  # recent frames; frames[0] starts at buf_off
        self.buf_off = 0  # sample index of frames[0]
        self.pos = 0  # samples consumed
        self.energy = []  # per frame since seg_start: (offset, energy)
        self.in_speech = False
        self.seg_start = 0
        self.voiced = 0
        self.last_voiced_end = 0
        self.floor = 0  # no segment may start before this (last cut)

    def _take(self, start, end):
        buf = np.concatenate(self.frames) if self.frames else np.zeros(0, np.float32)
        a, b = start - self.buf_off, end - self.buf_off
        return buf[max(0, a):b].copy()

    def _trim(self):
        keep_from = self.seg_start if self.in_speech else self.pos - self.pad_pre
        while self.frames and self.buf_off + len(self.frames[0]) <= keep_from:
            self.buf_off += len(self.frames.pop(0))

    def _emit(self, start, end):
        self.floor = end
        if self.voiced < self.min_speech:
            return None
        return (start, end, self._take(start, end))

    def feed(self, frame):
        """frame: FRAME float32 samples. Returns a list of closed segments."""
        out = []
        p = self.vad(frame)
        start = self.pos
        self.frames.append(frame)
        self.pos += len(frame)
        e = float(np.dot(frame, frame))
        if not self.in_speech:
            if p >= self.on:
                self.in_speech = True
                self.seg_start = max(start - self.pad_pre, self.floor, self.buf_off)
                self.voiced = len(frame)
                self.last_voiced_end = self.pos
                self.energy = [(start, e)]
        else:
            self.energy.append((start, e))
            if p >= self.off:
                self.voiced += len(frame)
                self.last_voiced_end = self.pos
            if self.pos - self.last_voiced_end >= self.pause:
                end = min(self.last_voiced_end + self.pad_post, self.pos)
                seg = self._emit(self.seg_start, end)
                if seg:
                    out.append(seg)
                self.in_speech = False
            elif self.pos - self.seg_start >= self.max_len:
                cut = self._quietest_cut()
                seg = self._emit(self.seg_start, cut)
                if seg:
                    out.append(seg)
                self.seg_start = cut
                self.energy = [(o, x) for o, x in self.energy if o >= cut]
                self.voiced = sum(FRAME for _ in self.energy)
        self._trim()
        return out

    def _quietest_cut(self):
        lo = self.seg_start + int(self.max_len * 0.6)
        cand = [(o, x) for o, x in self.energy if o >= lo]
        if len(cand) < 3:
            return self.pos
        win = [cand[i][1] + cand[i + 1][1] + cand[i + 2][1]
               for i in range(len(cand) - 2)]
        i = int(np.argmin(win))
        return cand[i + 1][0] + FRAME // 2

    def flush(self):
        if not self.in_speech:
            return []
        self.in_speech = False
        end = min(self.last_voiced_end + self.pad_post, self.pos)
        seg = self._emit(self.seg_start, end)
        return [seg] if seg else []

    @property
    def speaking(self):
        return self.in_speech


# --- audio helpers ------------------------------------------------------------
def wav_bytes(samples):
    pcm = (np.clip(samples, -1, 1) * 32767).astype(np.int16).tobytes()
    bio = io.BytesIO()
    with wave.open(bio, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(RATE)
        w.writeframes(pcm)
    return bio.getvalue()


def read_wav(path):
    with wave.open(path) as w:
        if w.getsampwidth() != 2:
            raise SystemExit("expected a 16-bit PCM WAV")
        ch, rate = w.getnchannels(), w.getframerate()
        frames = w.readframes(w.getnframes())
    s = np.frombuffer(frames, dtype=np.int16).astype(np.float32) / 32768.0
    if ch > 1:
        s = s[: len(s) // ch * ch].reshape(-1, ch).mean(axis=1)
    if rate != RATE:
        n = int(len(s) * RATE / rate)
        s = np.interp(np.linspace(0, len(s), n, endpoint=False),
                      np.arange(len(s)), s).astype(np.float32)
    return s


def pcm_to_float(b):
    return np.frombuffer(b, dtype=np.int16).astype(np.float32) / 32768.0


# --- text ---------------------------------------------------------------------
NO_SPACE_BEFORE = set(".,;:!?)]}…%،؛؟")
TAGS = re.compile(r"\[[^\]]*\]|^\s*\([^)]*\)\s*$|^\s*\*[^*]*\*\s*$")


def clean(text):
    text = TAGS.sub("", text or "")
    return " ".join(text.split())


def joined(prev, text):
    """The text to type after `prev` (already typed in this session)."""
    if not prev or not text or text[0] in NO_SPACE_BEFORE or prev[-1].isspace():
        return text
    return " " + text


