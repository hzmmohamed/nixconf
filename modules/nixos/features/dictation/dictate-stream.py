"""dictate-stream: segment-streaming dictation session for `dictate`.

One recording runs continuously; Silero VAD cuts it at natural pauses
(`pause_ms` of silence) or, in continuous speech, at the quietest point
before `max_segment_sec`. Each segment is transcribed as soon as it closes
(the session's backend: the first reachable whisper-server, else the local
engine) while recording goes on, and committed in order: typed into the
focused window, appended to the journal, recorded in the session dir.

  dictate-stream record [--lang L] [--t0 MS]   live session (SIGUSR1/SIGTERM
                                               stop and flush, SIGUSR2 cancels)
  dictate-stream file WAV [--stream] [--realtime] [--overlay]
  dictate-stream recover [--type]              transcribe leftover sessions

Crash safety: the raw audio of a session ($XDG_RUNTIME_DIR/dictate/
sessions/<id>/audio.raw, s16le 16 kHz mono) and its commit log stay until
every segment is committed; a crash loses at most the segment in flight,
and `recover` transcribes whatever was not committed.

Config: JSON file in $DICTATE_CONFIG (generated by the dictation feature);
DICTATE_SERVERS (space separated, may be empty), DICTATE_LANG and
DICTATE_OUTPUT (type|paste|print) override it.
"""

