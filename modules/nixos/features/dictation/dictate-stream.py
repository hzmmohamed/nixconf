def set_pdeathsig():
    """Children die with the session (no orphaned recorder/overlay).

    PR_SET_PDEATHSIG fires when the forking *thread* exits: only for
    children started from the main thread."""
    import ctypes
    ctypes.CDLL("libc.so.6", use_errno=True).prctl(1, signal.SIGTERM)


def start_recorder():
    rec = subprocess.Popen(
        [CFG["bin"]["pw-record"], "--rate", str(RATE), "--channels", "1",
         "--format", "s16", "--media-role", "Communication", "--raw", "-"],
        stdout=subprocess.PIPE, stderr=subprocess.DEVNULL,
        preexec_fn=set_pdeathsig)
    try:  # 1 MB pipe = 32 s of audio: room while the models load
        import fcntl
        fcntl.fcntl(rec.stdout.fileno(), 1031, 1 << 20)  # F_SETPIPE_SZ
    except OSError:
        pass
    return rec


