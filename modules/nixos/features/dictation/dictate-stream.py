class Session:
    """Segments in, transcripts out in order; every step lands in the draft."""

    def __init__(self, draft, mode, overlay, stream_print):
        self.draft = draft
        self.sid = draft.meta["sid"]
        self.lang = draft.meta["lang"]
        self.t0 = draft.meta["t0"]
        self.mode = mode
        self.journal = draft.meta["journal"]
        self.stream_print = stream_print
        self.input = draft.meta.get("input") or ""
        self.backends = Backends(self.lang, on_change=self.changed)
        self.lock = threading.Lock()
        self.next_index = 0  # next segment to be dispatched
        self.next_commit = 0
        self.results = {}
        self.meta = {}  # index -> (start, end, closed_wall)
        self.typed = ""  # stream: what was typed this session
        self.texts = []  # every transcribed segment, in order
        self.lines = []  # last committed texts (overlay, stream mode)
        self.failures = 0
        self.error = None  # why the session stopped itself (no sound, no audio)
        self.cancelled = False
        self.latencies = []
        self.work = queue.Queue()
        self.workers = [threading.Thread(target=self._worker, daemon=True)
                        for _ in range(CFG["workers"])]
        for w in self.workers:
            w.start()
        self.overlay = None
        self.ov_lock = threading.Lock()
        if overlay and CFG["bin"].get("overlay"):
            self._spawn_overlay()
        self.level = 0.0
        self.speaking = False
        self.warning = ""
        self.state = "recording"
        threading.Thread(target=self.backends.probe, daemon=True).start()

    # overlay ---------------------------------------------------------------
    def _spawn_overlay(self):
        try:
            argv = shlex.split(CFG["bin"]["overlay"])
            argv += ["--css", CFG["overlay"]["css"],
                     "--long-session-sec", str(CFG["overlay"]["long_session_sec"])]
            self.overlay = subprocess.Popen(
                argv,
                stdin=subprocess.PIPE, stdout=subprocess.DEVNULL,
                stderr=open(os.path.join(STATE_DIR, "overlay.log"), "w"),
                preexec_fn=set_pdeathsig)
        except OSError as err:
            log(f"overlay: {err}")

    def changed(self):
        if self.backends.ready.is_set():
            try:
                self.draft.save(backend=self.backends.label)
            except OSError:
                pass
        self.push()

    def push(self):
        ov = self.overlay
        if not ov or ov.poll() is not None:
            return
        with self.lock:
            msg = {"t": round(time.time() - self.t0, 2), "level": round(self.level, 3),
                   "speech": self.speaking, "lang": self.lang.upper(), "mode": self.mode,
                   "backend": self.backends.label, "input": self.input,
                   "warning": self.warning, "tier": self.draft.meta.get("tier", "personal"),
                   "lines": self.lines[-3:] if self.mode == "stream" else [],
                   "done": self.next_commit, "total": self.next_index,
                   "failed": self.failures, "state": self.state}
        line = (json.dumps(msg, ensure_ascii=False) + "\n").encode()
        with self.ov_lock:
            try:
                ov.stdin.write(line)
                ov.stdin.flush()
            except (OSError, ValueError):
                self.overlay = None

    def close_overlay(self):
        if self.overlay:
            with self.ov_lock:
                try:
                    self.overlay.stdin.close()
                except OSError:
                    pass

    # audio in --------------------------------------------------------------
    def submit(self, seg, now_wall):
        start, end, samples = seg
        with self.lock:
            i = self.next_index
            self.next_index += 1
            self.meta[i] = (start, end, now_wall)
        self.work.put((i, samples))
        self.push()

    # transcription ---------------------------------------------------------
    def _worker(self):
        while True:
            item = self.work.get()
            if item is None:
                return
            i, samples = item
            text, ok, conf = "", False, None
            # Every segment gets a result, whatever happens: a gap would stall
            # the in-order commit.
            try:
                if not self.cancelled:
                    delay = float(os.environ.get("DICTATE_TEST_JITTER", "0"))
                    if delay:
                        time.sleep(random.uniform(0, delay))
                    context = join_texts(self.texts)[-200:]
                    prompt = (CFG["prompt"] + " " + context).strip()
                    raw, conf = self.backends.transcribe(samples, prompt)
                    text, ok = clean(raw), True
                    if delay:
                        log(f"segment {i} transcribed (next to commit: {self.next_commit})")
            except Exception as err:
                log(f"segment {i}: {err}")
            with self.lock:
                self.results[i] = (text, ok, conf)
            self._commit_ready()

    def _commit_ready(self):
        while True:
            with self.lock:
                i = self.next_commit
                if i not in self.results or self.cancelled:
                    return
                text, ok, conf = self.results.pop(i)
                start, end, closed = self.meta.pop(i)
            try:
                self._commit(i, start, end, closed, text, ok, conf)
            except Exception as err:
                log(f"commit {i}: {err}")
            finally:
                with self.lock:
                    self.next_commit += 1
            self.push()

    def _commit(self, i, start, end, closed, text, ok, conf=None):
        delivered = False
        if ok:
            self.texts.append(text)
            if self.mode == "stream" and text:
                out = joined(self.typed, text)
                if deliver(out):
                    self.typed += out
                    delivered = True
                else:
                    self.failures += 1
        else:
            self.failures += 1
        lat = time.time() - closed
        self.latencies.append(lat)
        self.draft.sync()  # audio up to here is on disk before the commit is
        self.draft.add_commit(commit_entry(i, start, end, ok, text,
                                           delivered or (ok and not text), conf))
        if text:
            with self.lock:
                self.lines.append(text)
                del self.lines[:-3]
            if delivered and self.journal:
                journal_append(self.sid, text)
        if self.stream_print:
            print(f"[{fmt_t(start / RATE)}.{int(start / RATE * 10) % 10}"
                  f"–{fmt_t(end / RATE)}.{int(end / RATE * 10) % 10}] #{i} "
                  f"+{lat:.2f}s {'' if ok else '(FAILED) '}{text}", flush=True)

    # end -------------------------------------------------------------------
    def drain(self):
        """Wait until every dispatched segment is committed."""
        while True:
            with self.lock:
                if self.next_commit >= self.next_index or self.cancelled:
                    break
            time.sleep(0.02)

    def _stop_workers(self):
        for _ in self.workers:
            self.work.put(None)
        self.backends.close()

    def cancel(self):
        self.cancelled = True
        self._stop_workers()
        self.close_overlay()
        self.draft.close_audio()
        if self.draft.duration() < 0.5 and not self.texts:
            self.draft.discard()
            return
        self.draft.save(status="cancelled", duration=round(self.draft.duration(), 2))
        notify(f"Cancelled; the recording is kept for {CFG['keep_days']} days in "
               "“Dictation drafts”.", "low", 4000)

    def conclude(self):
        """After drain: deliver (batch), then mark the draft done or pending.

        Returns the final status ("done", "pending", "empty")."""
        self._stop_workers()
        d = self.draft
        d.close_audio()
        n = self.next_index
        duration = round(d.duration(), 2)
        if n == 0:
            self.close_overlay()
            d.discard()  # no speech: nothing worth keeping
            if d.meta["source"] == "mic" and not self.error:
                notify(f"Nothing heard from {self.input or 'the mic'}", "normal", 4000)
            return "empty"
        reason = None
        if self.failures:
            reason = f"{self.failures} of {n} segments failed"
        elif self.mode == "batch":
            text = join_texts(self.texts)
            if not text:
                reason = "the transcript is empty"
            else:
                with self.lock:
                    self.state = "typing"
                self.push()
                # Batch pastes the whole text at once (typing it trickles in).
                how = deliver(text + (" " if CFG["append_space"] else ""),
                              "paste" if CFG["output"] in ("type", "paste") else None)
                if how:
                    d.set_commits([dict(c, delivered=True) for c in d.commits()])
                    d.save(delivered=how)
                    if self.journal:
                        journal_append(self.sid, text)
                else:
                    reason = "couldn't type or copy the text"
        elif self.typed and CFG["append_space"]:
            deliver(" ")
        self.close_overlay()
        if reason:
            d.save(status="pending", complete=True, error=reason, duration=duration)
            if d.meta["source"] == "mic":
                notify(f"Draft not delivered ({reason}); the recording is saved. Open "
                       "“Dictation drafts” in the launcher, or run "
                       "`dictate recover --latest --type`.", "critical", 0)
            return "pending"
        if d.meta["source"] == "file":
            d.discard()
        else:
            d.save(status="done", complete=True, error=None, duration=duration)
        return "done"


def stats(lat):
    if not lat:
        return "no segments"
    a = sorted(lat)
    return (f"{len(a)} segments, commit latency after close: median {a[len(a) // 2]:.2f}s, "
            f"max {a[-1]:.2f}s")


def segment_all(samples, offset=0):
    seg = Segmenter(Vad(CFG["vad_model"]), CFG["pause_ms"], CFG["max_segment_sec"])
    out = []
    for k in range(0, len(samples) - FRAME + 1, FRAME):
        out += seg.feed(samples[k:k + FRAME])
    out += seg.flush()
    return [(a + offset, b + offset, s) for a, b, s in out]


