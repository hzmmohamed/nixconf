class UnixHTTPConnection(http.client.HTTPConnection):
    def __init__(self, path, timeout):
        super().__init__("local", timeout=timeout)
        self.path = path

    def connect(self):
        self.sock = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
        self.sock.settimeout(self.timeout)
        self.sock.connect(self.path)


def http_request(url, method="GET", body=None, headers=None, timeout=20,
                 unix=None):
    if unix:
        conn = UnixHTTPConnection(unix, timeout)
        path = url
    else:
        u = urllib.parse.urlsplit(url)
        conn = http.client.HTTPConnection(u.hostname, u.port or 80, timeout=timeout)
        path = u.path or "/"
    try:
        conn.request(method, path, body=body, headers=headers or {})
        r = conn.getresponse()
        data = r.read()
        if r.status != 200:
            raise OSError(f"HTTP {r.status}: {data[:200]!r}")
        return data
    finally:
        conn.close()


def multipart(fields, wav):
    boundary = uuid.uuid4().hex
    parts = []
    for k, v in fields.items():
        parts.append(f'--{boundary}\r\nContent-Disposition: form-data; name="{k}"'
                     f"\r\n\r\n{v}\r\n".encode())
    parts.append(f'--{boundary}\r\nContent-Disposition: form-data; name="file"; '
                 f'filename="segment.wav"\r\nContent-Type: audio/wav\r\n\r\n'.encode())
    parts.append(wav)
    parts.append(f"\r\n--{boundary}--\r\n".encode())
    return b"".join(parts), {"Content-Type": f"multipart/form-data; boundary={boundary}"}


def reachable(url, timeout=20):
    """GET / with a short connect timeout; a cold server loads meanwhile."""
    u = urllib.parse.urlsplit(url)
    try:
        s = socket.create_connection((u.hostname, u.port or 80), timeout=0.6)
        s.close()
        http_request(url + "/", timeout=timeout)
        return True
    except OSError:
        return False


def host_label(url):
    host = urllib.parse.urlsplit(url).hostname or url
    if host in ("127.0.0.1", "localhost", "::1"):
        host = socket.gethostname()
    return re.sub(r"-(cable|lan|wifi)$", "", host)


def free_port():
    s = socket.socket()
    s.bind(("127.0.0.1", 0))
    port = s.getsockname()[1]
    s.close()
    return port


class Backends:
    """The session's backend: probed once, falls back to local on failure."""

    def __init__(self, lang, on_change=None):
        self.lang = lang
        self.on_change = on_change or (lambda: None)
        self.ready = threading.Event()
        self.url = None  # remote whisper-server, or None for local
        self.local_whisper = None  # (Popen, url) for non-English offline
        self.lock = threading.Lock()
        self.stopped = False

    @property
    def label(self):
        if not self.ready.is_set():
            return "connecting…"
        if self.url:
            return f"{host_label(self.url)} GPU"
        if self.lang == CFG["local_lang"]:
            return "local CPU"
        return "local iGPU" if CFG.get("whisper_model") else "no engine"

    def probe(self):
        servers = CFG["servers"]
        ok = [None] * len(servers)

        def check(i, url):
            ok[i] = reachable(url)

        threads = [threading.Thread(target=check, args=(i, u), daemon=True)
                   for i, u in enumerate(servers)]
        for t in threads:
            t.start()
        for i, t in enumerate(threads):
            t.join(25)
            if ok[i]:
                self.url = servers[i]
                break
        if not self.url:
            self._warm_local()
        self.ready.set()
        self.on_change()

    def _warm_local(self):
        if self.lang == CFG["local_lang"]:
            try:
                http_request("/ready", unix=CFG["local_socket"], timeout=60)
            except OSError as err:
                log(f"local engine: {err}")
        elif CFG.get("whisper_model"):
            self._start_local_whisper()

    def _start_local_whisper(self):
        """A resident whisper-server (Vulkan iGPU) for this session only."""
        with self.lock:
            if self.local_whisper or self.stopped:
                return
            port = free_port()
            # Started from a worker thread, so no PDEATHSIG: a shell holds
            # our pipe and stops the server when it closes (session end or
            # crash alike).
            watchdog = 'exec 3<&0; "$@" </dev/null & p=$!; read -r _ <&3; kill $p'
            proc = subprocess.Popen(
                ["/bin/sh", "-c", watchdog, "sh", CFG["bin"]["whisper-server"],
                 "--host", "127.0.0.1", "--port", str(port),
                 "--model", CFG["whisper_model"], "--threads", str(CFG["threads"]),
                 "--suppress-nst"],
                stdin=subprocess.PIPE, stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL, start_new_session=True)
            self.local_whisper = (proc, f"http://127.0.0.1:{port}")
        url = self.local_whisper[1]
        for _ in range(300):
            if proc.poll() is not None:
                log("local whisper-server exited")
                return
            try:
                http_request(url + "/", timeout=2)
                return
            except OSError:
                time.sleep(0.1)

    def keepalive(self):
        """Keep the server (or the local engine) from idle-stopping."""
        if self.url:
            reachable(self.url, timeout=5)
        elif self.lang == CFG["local_lang"]:
            try:
                http_request("/ready", unix=CFG["local_socket"], timeout=5)
            except OSError:
                pass

    def _whisper(self, url, samples, prompt):
        fields = {"response_format": "verbose_json", "language": self.lang,
                  "temperature": "0.0", "temperature_inc": "0.2"}
        if prompt:
            fields["prompt"] = prompt
        body, headers = multipart(fields, wav_bytes(samples))
        return parse_inference(json.loads(http_request(url + "/inference", "POST", body,
                                                       headers, timeout=120)))

    def _local(self, samples):
        if self.lang == CFG["local_lang"]:
            data = http_request("/inference", "POST", wav_bytes(samples),
                                {"Content-Type": "audio/wav"},
                                unix=CFG["local_socket"], timeout=120)
            return json.loads(data)["text"], None
        if not CFG.get("whisper_model"):
            raise OSError(f"no local model for '{self.lang}' (needs a server)")
        if not self.local_whisper:
            self._start_local_whisper()
        return self._whisper(self.local_whisper[1], samples, "")

    def transcribe(self, samples, prompt=""):
        """(text, conf): conf is Whisper's confidence (parse_inference) or None."""
        self.ready.wait()
        url = self.url
        if url:
            try:
                return self._whisper(url, samples, prompt)
            except (OSError, ValueError, KeyError) as err:
                log(f"{host_label(url)} failed ({err}); local engine from now on")
                with self.lock:
                    if self.url == url:
                        self.url = None
                self.on_change()
        return self._local(samples)

    def close(self):
        with self.lock:
            self.stopped = True
            if self.local_whisper:
                try:
                    self.local_whisper[0].stdin.close()
                except OSError:
                    pass


