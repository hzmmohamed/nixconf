def fsync_dir(path):
    fd = os.open(path, os.O_RDONLY | os.O_DIRECTORY)
    try:
        os.fsync(fd)
    finally:
        os.close(fd)


def atomic_write(path, data):
    tmp = path + ".tmp"
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    try:
        os.write(fd, data.encode() if isinstance(data, str) else data)
        os.fsync(fd)
    finally:
        os.close(fd)
    os.replace(tmp, path)
    fsync_dir(os.path.dirname(path))


def alive(pid):
    try:
        with open(f"/proc/{int(pid)}/cmdline", "rb") as f:
            return b"dictate-stream" in f.read()
    except (OSError, ValueError, TypeError):
        return False


def join_texts(texts):
    out = ""
    for t in texts:
        out += joined(out, t)
    return out


class Draft:
    """One recording on persistent disk, from the first sample to delivery."""

    def __init__(self, path, meta):
        self.path = path
        self.meta = meta
        self.lock = threading.Lock()
        self.audio_fd = None

    @classmethod
    def create(cls, lang, mode, source, journal, t0, app="", tier="personal"):
        os.makedirs(DRAFTS, mode=0o700, exist_ok=True)
        sid = uuid.uuid4().hex[:4]
        name = time.strftime("%Y-%m-%d_%H%M%S", time.localtime(t0)) + "-" + sid
        path = os.path.join(DRAFTS, name)
        os.makedirs(path, mode=0o700)
        d = cls(path, {
            "id": name, "sid": sid,
            "started": time.strftime("%Y-%m-%dT%H:%M:%S%z", time.localtime(t0)),
            "t0": t0, "lang": lang, "mode": mode, "source": source,
            "journal": journal, "status": "recording", "pid": os.getpid(),
            "backend": None, "complete": False, "error": None, "delivered": None,
            "app": app, "tier": tier, "origin": socket.gethostname(),
            "prompt_sha": prompt_sha(CFG["prompt"]),
            "audio": {"file": "audio.pcm", "format": "s16le", "rate": RATE, "channels": 1},
        })
        d.audio_fd = os.open(os.path.join(path, "audio.pcm"),
                             os.O_WRONLY | os.O_CREAT | os.O_APPEND, 0o600)
        d.save()
        return d

    @classmethod
    def load(cls, path):
        name = os.path.basename(path)
        meta = {"id": name, "sid": name.rsplit("-", 1)[-1], "status": "recording",
                "pid": 0, "lang": CFG["default_lang"], "mode": CFG["mode"],
                "source": "mic", "journal": True, "complete": False}
        try:
            with open(os.path.join(path, "meta.json")) as f:
                meta.update(json.load(f))
        except (OSError, ValueError):
            pass  # no or unreadable meta: reconstructed from the directory name
        return cls(path, meta)

    @property
    def id(self):
        return self.meta["id"]

    def file(self, name):
        return os.path.join(self.path, name)

    def save(self, **updates):
        with self.lock:
            self.meta.update(updates)
            atomic_write(self.file("meta.json"),
                         json.dumps(self.meta, ensure_ascii=False, indent=1) + "\n")

    @property
    def status(self):
        """Stored status; a session that died mid-way reads as `interrupted`."""
        st = self.meta.get("status", "pending")
        if st in ("recording", "transcribing") and not alive(self.meta.get("pid", 0)):
            return "interrupted"
        return st

    @property
    def needs_attention(self):
        return self.status in ("pending", "interrupted")

    # audio
    def write_audio(self, pcm):
        os.write(self.audio_fd, pcm)

    def sync(self):
        fd = self.audio_fd
        if fd is not None:
            try:
                os.fsync(fd)
            except OSError:
                pass

    def close_audio(self):
        if self.audio_fd is not None:
            self.sync()
            os.close(self.audio_fd)
            self.audio_fd = None

    def duration(self):
        if os.path.exists(self.file("audio.pcm")):
            return os.path.getsize(self.file("audio.pcm")) / 2 / RATE
        return float(self.meta.get("duration") or 0)

    def samples(self):
        """The audio as float32; a write cut short by a power loss is fine."""
        if os.path.exists(self.file("audio.pcm")):
            with open(self.file("audio.pcm"), "rb") as f:
                data = f.read()
            return pcm_to_float(data[: len(data) // 2 * 2])
        if os.path.exists(self.file("audio.opus")):
            import tempfile
            with tempfile.TemporaryDirectory() as tmp:
                wav = os.path.join(tmp, "a.wav")
                subprocess.run([CFG["bin"]["opusdec"], "--quiet", "--rate", str(RATE),
                                self.file("audio.opus"), wav], check=True)
                return read_wav(wav)
        return np.zeros(0, dtype=np.float32)

    def compress(self):
        """Terminal drafts keep Opus (24 kb/s speech, ~1/10 of the size)."""
        pcm = self.file("audio.pcm")
        if not os.path.exists(pcm) or not CFG["bin"].get("opusenc"):
            return
        tmp = self.file("audio.opus.tmp")
        try:
            subprocess.run([CFG["bin"]["opusenc"], "--quiet", "--raw", "--raw-bits", "16",
                            "--raw-rate", str(RATE), "--raw-chan", "1", "--bitrate", "24",
                            "--speech", pcm, tmp], check=True, timeout=600,
                           preexec_fn=lambda: os.nice(10))
            os.chmod(tmp, 0o600)
            fd = os.open(tmp, os.O_RDONLY)
            os.fsync(fd)
            os.close(fd)
            os.replace(tmp, self.file("audio.opus"))
            fsync_dir(self.path)
            self.save(duration=round(os.path.getsize(pcm) / 2 / RATE, 2),
                      audio={"file": "audio.opus", "format": "opus", "rate": RATE, "channels": 1})
            os.unlink(pcm)
        except (OSError, subprocess.SubprocessError) as err:
            log(f"compress {self.id}: {err} (raw audio kept)")

    # transcript
    def commits(self):
        out = []
        try:
            with open(self.file("commits.jsonl")) as f:
                for line in f:
                    try:
                        out.append(json.loads(line))
                    except ValueError:
                        pass  # a line cut short by a crash
        except OSError:
            pass
        return out

    def add_commit(self, entry):
        with self.lock:
            fd = os.open(self.file("commits.jsonl"), os.O_WRONLY | os.O_APPEND | os.O_CREAT, 0o600)
            try:
                os.write(fd, (json.dumps(entry, ensure_ascii=False) + "\n").encode())
                os.fsync(fd)
            finally:
                os.close(fd)
        self.write_transcript()

    def set_commits(self, commits):
        commits = sorted(commits, key=lambda c: c["start"])
        with self.lock:
            atomic_write(self.file("commits.jsonl"), "".join(
                json.dumps(c, ensure_ascii=False) + "\n" for c in commits))
        self.write_transcript()

    def transcript(self):
        return join_texts(c["text"] for c in sorted(self.commits(), key=lambda c: c["start"])
                          if c.get("ok") and c.get("text"))

    def write_transcript(self):
        text = self.transcript()
        with self.lock:
            atomic_write(self.file("transcript.txt"), text + "\n" if text else "")

    def discard(self):
        shutil.rmtree(self.path, ignore_errors=True)


def list_drafts():
    if not os.path.isdir(DRAFTS):
        return []
    names = sorted((n for n in os.listdir(DRAFTS) if os.path.isdir(os.path.join(DRAFTS, n))),
                   reverse=True)
    return [Draft.load(os.path.join(DRAFTS, n)) for n in names]


def find_draft(ident):
    drafts = list_drafts()
    exact = [d for d in drafts if d.id == ident]
    if exact:
        return exact[0]
    hits = [d for d in drafts if ident in d.id]
    if len(hits) == 1:
        return hits[0]
    raise SystemExit(f"dictate: {'no' if not hits else 'more than one'} draft matches '{ident}'")


def prune(keep_days=None):
    """Drop delivered/cancelled drafts older than keep_days, and empty ones.
    With a training lab (lab_url), a delivered draft not uploaded yet is kept
    until unsent_days: butternut being off must not lose it."""
    keep = CFG["keep_days"] if keep_days is None else keep_days
    unsent = CFG.get("unsent_days", 30)
    now = time.time()
    removed = 0
    for d in list_drafts():
        st = d.status
        try:
            age = now - os.path.getmtime(d.file("meta.json"))
        except OSError:
            age = now - os.path.getmtime(d.path)
        empty = st == "interrupted" and d.duration() < 0.5 and not d.commits()
        limit = keep
        if CFG.get("lab_url") and st == "done" and not d.meta.get("uploaded"):
            limit = max(keep, unsent)
        if (st in TERMINAL and age > limit * 86400) or (empty and age > 60):
            d.discard()
            removed += 1
    return removed


# --- training lab -----------------------------------------------------------
def push(d, url, timeout=10):
    """Upload a delivered draft to the lab's inbox (dictation-lab feature):
    PUT meta.json, commits.jsonl and the audio, then POST done; mark it
    uploaded. False (and the draft stays unsent) on any failure. The text
    is never logged."""
    if d.status != "done" or d.meta.get("uploaded"):
        return False
    base = f"{url.rstrip('/')}/inbox/{socket.gethostname().lower()}/{d.id}"
    files = ["meta.json", "commits.jsonl"]
    files += [a for a in ("audio.opus", "audio.pcm") if os.path.exists(d.file(a))][:1]
    try:
        for name in files:
            if not os.path.exists(d.file(name)):
                continue
            with open(d.file(name), "rb") as f:
                data = f.read()
            req = urllib.request.Request(f"{base}/{name}", data=data, method="PUT")
            urllib.request.urlopen(req, timeout=timeout).close()
        req = urllib.request.Request(f"{base}/done", data=b"", method="POST")
        urllib.request.urlopen(req, timeout=max(timeout, 60)).close()
    except (OSError, urllib.error.URLError, ValueError) as err:
        log(f"push {d.id}: {getattr(err, 'code', None) or type(err).__name__}")
        return False
    d.save(uploaded=int(time.time()))
    return True


