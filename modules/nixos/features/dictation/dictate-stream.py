# WirePlumber 0.5 exposes each connected Bluetooth headset as a virtual
# source `bluez_input.<MAC>` (a loopback), present even while the headset is
# in its playback (A2DP) profile; recording from it makes WirePlumber switch
# the headset to its headset (HFP) profile and back afterwards. So choosing a
# headset is just choosing that node.
INPUT_FILE = os.path.join(os.path.expanduser(CFG["journal_dir"]), "input")


def pw_dump():
    try:
        out = subprocess.run([CFG["bin"]["pw-dump"]], capture_output=True, timeout=5)
        return json.loads(out.stdout or b"[]")
    except (OSError, ValueError, subprocess.SubprocessError):
        return []


def list_inputs(objs):
    """Recordable sources, headsets first (most recently connected first).

    [{name, label, kind: headset|mic, serial}] and the default source's name."""
    headsets = {}  # bluez address -> (serial, description)
    default = None
    for o in objs:
        props = (o.get("info") or {}).get("props") or {}
        if o.get("type") == "PipeWire:Interface:Device" and props.get("device.api") == "bluez5":
            addr = props.get("api.bluez5.address") or props.get("device.name", "")[len("bluez_card."):].replace("_", ":")
            headsets[addr] = (int(props.get("object.serial", 0)),
                              props.get("device.description") or addr)
        if o.get("type") == "PipeWire:Interface:Metadata" and (o.get("props") or {}).get("metadata.name") == "default":
            for m in o.get("metadata") or []:
                if m.get("key") == "default.audio.source":
                    v = m.get("value")
                    default = v.get("name") if isinstance(v, dict) else None
    out, seen = [], set()
    for o in objs:
        props = (o.get("info") or {}).get("props") or {}
        if o.get("type") != "PipeWire:Interface:Node" or props.get("media.class") != "Audio/Source":
            continue
        name = props.get("node.name", "")
        label = props.get("node.description") or props.get("node.nick") or name
        if name.startswith("alsa_input.pci-") and props.get("node.nick"):
            label = "Built-in " + props["node.nick"].lower()  # not the chipset name
        if name.startswith("bluez_input."):
            addr = name[len("bluez_input."):].split(".")[0].replace("_", ":")
            if addr in seen:
                continue
            seen.add(addr)
            serial, desc = headsets.get(addr, (int(props.get("object.serial", 0)), label))
            out.append({"name": name, "label": desc, "kind": "headset", "serial": serial})
        else:
            out.append({"name": name, "label": label, "kind": "mic",
                        "serial": int(props.get("object.serial", 0))})
    out.sort(key=lambda i: (i["kind"] != "headset", -i["serial"] if i["kind"] == "headset" else 0))
    return out, default


def preferred_input():
    try:
        with open(INPUT_FILE) as f:
            return f.read().strip() or None
    except OSError:
        return None


def resolve_input(objs=None, pref=None):
    """The session's input: {name (None: the default source), label, kind, note}.

    A preferred source if connected, else the most recently connected
    headset, else the default source."""
    objs = pw_dump() if objs is None else objs
    inputs, default = list_inputs(objs)
    note = None
    if pref and pref != "auto":
        for i in inputs:
            if i["name"] == pref:
                return dict(i, note=None)
        note = "the chosen mic isn't connected"
    for i in inputs:
        if i["kind"] == "headset":
            return dict(i, note=note)
    if not inputs:
        return {"name": None, "label": "no microphone", "kind": "none", "note": note}
    label = next((i["label"] for i in inputs if i["name"] == default), None)
    return {"name": None, "label": label or "default input", "kind": "mic", "note": note}


def start_recorder(target=None):
    argv = [CFG["bin"]["pw-record"], "--rate", str(RATE), "--channels", "1",
            "--format", "s16", "--media-role", "Communication", "--raw"]
    if target:
        argv += ["--target", target]
    rec = subprocess.Popen(
        argv + ["-"],
        stdout=subprocess.PIPE, stderr=subprocess.DEVNULL,
        preexec_fn=set_pdeathsig)
    try:  # 1 MB pipe = 32 s of audio: room while the models load
        import fcntl
        fcntl.fcntl(rec.stdout.fileno(), 1031, 1 << 20)  # F_SETPIPE_SZ
    except OSError:
        pass
    return rec


