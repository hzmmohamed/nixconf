def write_state(state):
    """The bar/key state, only while this process is the current session."""
    import fcntl
    os.makedirs(STATE_DIR, exist_ok=True)
    with open(os.path.join(STATE_DIR, "lock"), "a") as lk:
        fcntl.flock(lk, fcntl.LOCK_EX)
        try:
            with open(os.path.join(STATE_DIR, "pid")) as f:
                if f.read().strip() != str(os.getpid()):
                    return
        except OSError:
            return
        with open(os.path.join(STATE_DIR, "state"), "w") as f:
            f.write(state)


