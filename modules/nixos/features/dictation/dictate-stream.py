def cmd_record(args):
    rec = RECORDER
    stop = {"why": None}

    def on_signal(sig, _frame):
        stop["why"] = "cancel" if sig == signal.SIGUSR2 else "stop"
        try:
            rec.terminate()
        except OSError:
            pass

    for s in (signal.SIGUSR1, signal.SIGTERM, signal.SIGINT, signal.SIGUSR2):
        signal.signal(s, on_signal)

    lang = args.lang or os.environ.get("DICTATE_LANG") or CFG["default_lang"]
    t0 = (args.t0 / 1000.0) if args.t0 else time.time()
    sess = Session(lang, t0, "mic", journal=True, overlay=CFG["overlay"]["enable"],
                   stream_print=False)
    seg = Segmenter(Vad(CFG["vad_model"]), CFG["pause_ms"], CFG["max_segment_sec"])
    bar = Bar()
    bar.refresh()

    def check_leftovers():
        n = len([1 for d, _ in leftovers() if d != sess.dir])
        if n:
            notify(f"{n} unfinished dictation session(s) left from a crash: "
                   "run `dictate recover` to get the text back.", "normal", 8000)

    threading.Thread(target=check_leftovers, daemon=True).start()
    if not CFG["overlay"]["enable"]:
        notify(f"Listening ({lang.upper()})…", "low", 3000)
    max_sec = CFG["max_sec"]
    last_tick = last_push = time.monotonic()
    last_keep = last_tick
    level_acc, level_n = 0.0, 0
    pending = b""
    fd = rec.stdout.fileno()
    while True:
        data = os.read(fd, 4096)
        if not data:
            break
        sess.save_audio(data)
        pending += data
        n = len(pending) // BYTES_PER_FRAME * BYTES_PER_FRAME
        frames, pending = pending[:n], pending[n:]
        for k in range(0, n, BYTES_PER_FRAME):
            f = pcm_to_float(frames[k:k + BYTES_PER_FRAME])
            level_acc += float(np.dot(f, f))
            level_n += len(f)
            for s in seg.feed(f):
                sess.submit(s, time.time())
        now = time.monotonic()
        if now - last_push >= 1 / 15 and level_n:
            rms = (level_acc / level_n) ** 0.5
            # -60 dBFS .. -12 dBFS -> 0..1
            db = 20 * np.log10(max(rms, 1e-6))
            sess.level = float(min(1.0, max(0.0, (db + 60) / 48)))
            sess.speaking = seg.speaking
            level_acc, level_n = 0.0, 0
            sess.push()
            last_push = now
        if now - last_tick >= 1:
            bar.refresh()
            last_tick = now
        if now - last_keep >= 60:
            threading.Thread(target=sess.backends.keepalive, daemon=True).start()
            last_keep = now
        if time.time() - t0 >= max_sec and stop["why"] is None:
            stop["why"] = "stop"
            notify(f"Stopped at the {max_sec // 60} min safety limit", "normal", 5000)
            rec.terminate()
    rec.wait()
    if stop["why"] == "cancel":
        write_state("idle")
        bar.refresh()
        sess.finish(cancelled=True)
        return
    write_state("transcribing")
    sess.state = "finishing"
    sess.speaking = False
    sess.level = 0.0
    bar.refresh()
    for s in seg.flush():
        sess.submit(s, time.time())
    sess.push()
    sess.drain()
    if sess.typed and CFG["append_space"]:
        type_text(" ")
    sess.finish()
    write_state("idle")
    bar.refresh()
    log(stats(sess.latencies))


def run_file(samples, args, sess):
    seg = Segmenter(Vad(CFG["vad_model"]), CFG["pause_ms"], CFG["max_segment_sec"])
    started = time.time()
    for k in range(0, len(samples) - FRAME + 1, FRAME):
        f = samples[k:k + FRAME]
        sess.save_audio((f * 32767).astype(np.int16).tobytes())
        for s in seg.feed(f):
            sess.submit(s, time.time())
        if args.realtime:
            ahead = (k + FRAME) / RATE - (time.time() - started)
            if ahead > 0:
                time.sleep(ahead)
            if k % (FRAME * 2) == 0:
                sess.level = float(min(1.0, max(0.0, (20 * np.log10(
                    max(float(np.sqrt(np.mean(f * f))), 1e-6)) + 60) / 48)))
                sess.speaking = seg.speaking
                sess.push()
    for s in seg.flush():
        sess.submit(s, time.time())
    sess.state = "finishing"
    sess.drain()


def cmd_file(args):
    samples = read_wav(args.wav)
    lang = os.environ.get("DICTATE_LANG") or CFG["default_lang"]
    CFG["output"] = "print" if not args.stream else "none"
    sess = Session(lang, time.time(), "file", journal=False, overlay=args.overlay,
                   stream_print=args.stream)
    sess.backends.ready.wait()
    log(f"{sess.backends.label} ({lang}), {len(samples) / RATE:.1f}s audio, "
        f"pause {CFG['pause_ms']} ms, max segment {CFG['max_segment_sec']} s")
    t = time.time()
    run_file(samples, args, sess)
    sess.finish()
    if not args.stream:
        print()
    log(f"{stats(sess.latencies)}; total {time.time() - t:.1f}s")


def alive(pid):
    try:
        with open(f"/proc/{pid}/cmdline", "rb") as f:
            return b"dictate-stream" in f.read()
    except OSError:
        return False


def leftovers():
    out = []
    if not os.path.isdir(SESSIONS):
        return out
    for sid in sorted(os.listdir(SESSIONS)):
        d = os.path.join(SESSIONS, sid)
        try:
            with open(os.path.join(d, "meta.json")) as f:
                meta = json.load(f)
        except (OSError, ValueError):
            meta = {"sid": sid, "pid": 0, "lang": CFG["default_lang"], "journal": True}
        if alive(meta.get("pid", 0)):
            continue
        out.append((d, meta))
    return out


def cmd_recover(args):
    found = leftovers()
    if args.list:
        for d, meta in found:
            size = os.path.getsize(os.path.join(d, "audio.raw")) if os.path.exists(
                os.path.join(d, "audio.raw")) else 0
            print(f"{meta['sid']}  {meta.get('lang', '?')}  {size / 2 / RATE:6.1f}s audio  {d}")
        return
    if not found:
        log("nothing to recover")
        return
    for d, meta in found:
        raw = os.path.join(d, "audio.raw")
        if not os.path.exists(raw):
            shutil.rmtree(d, ignore_errors=True)
            continue
        with open(raw, "rb") as f:
            data = f.read()
        samples = pcm_to_float(data[: len(data) // 2 * 2])
        commits = []
        try:
            with open(os.path.join(d, "commits.jsonl")) as f:
                commits = [json.loads(line) for line in f if line.strip()]
        except (OSError, ValueError):
            pass
        done_until = max([c["end"] for c in commits], default=0)
        ranges = [(c["start"], c["end"]) for c in commits if not c.get("ok", True)]
        ranges.append((done_until, len(samples)))
        lang = meta.get("lang") or CFG["default_lang"]
        backends = Backends(lang)
        backends.probe()
        log(f"session {meta['sid']}: {len(commits)} committed, recovering "
            f"{sum(b - a for a, b in ranges) / RATE:.1f}s on {backends.label}")
        texts = []
        ok_all = True
        for a, b in ranges:
            if b - a < RATE // 4:
                continue
            seg = Segmenter(Vad(CFG["vad_model"]), CFG["pause_ms"], CFG["max_segment_sec"])
            chunk = samples[a:b]
            segs = []
            for k in range(0, len(chunk) - FRAME + 1, FRAME):
                segs += seg.feed(chunk[k:k + FRAME])
            segs += seg.flush()
            for s in segs:
                try:
                    t = clean(backends.transcribe(s[2]))
                except (OSError, ValueError, KeyError) as err:
                    log(f"segment failed: {err}")
                    ok_all = False
                    continue
                if t:
                    texts.append(t)
        backends.close()
        text = ""
        for t in texts:
            text += joined(text, t)
        print(text)
        if args.type and text:
            type_text(text + (" " if CFG["append_space"] else ""))
        if text and meta.get("journal", True):
            journal_append(meta["sid"], text, note=" (recovered)")
        if ok_all:
            shutil.rmtree(d, ignore_errors=True)


def main():
    ap = argparse.ArgumentParser(prog="dictate-stream")
    sub = ap.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("record")
    r.add_argument("--lang")
    r.add_argument("--t0", type=int, help="key press time, ms since the epoch")
    f = sub.add_parser("file")
    f.add_argument("wav")
    f.add_argument("--stream", action="store_true", help="print segments as they commit")
    f.add_argument("--realtime", action="store_true", help="feed the file at speaking pace")
    f.add_argument("--overlay", action="store_true", help="show the live overlay")
    v = sub.add_parser("recover")
    v.add_argument("--type", action="store_true", help="also type the recovered text")
    v.add_argument("--list", action="store_true", help="only list leftover sessions")
    args = ap.parse_args()
    os.makedirs(SESSIONS, mode=0o700, exist_ok=True)
    {"record": cmd_record, "file": cmd_file, "recover": cmd_recover}[args.cmd](args)


if __name__ == "__main__":
    main()
